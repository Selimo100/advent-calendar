/**
 * Sets the password for the hidden dev mode (5 taps in the top-left corner).
 * Writes a salted SHA-256 hash to src/dev/devPassword.ts; the password itself
 * is never stored. Commit that file so the deployed site picks it up.
 *
 * Usage: npm run dev:password
 */
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { passwordHash } from '../src/lib/sha256.ts';

const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/dev/devPassword.ts');

/** Reads a line from the terminal without echoing it. */
function askHidden(question: string): Promise<string> {
  return new Promise((resolve) => {
    const stdin = process.stdin;
    process.stdout.write(question);
    let value = '';
    const isTTY = stdin.isTTY;
    if (isTTY) stdin.setRawMode(true);
    stdin.resume();
    stdin.setEncoding('utf8');
    const onData = (chunk: string) => {
      for (const char of chunk) {
        if (char === '\r' || char === '\n') {
          if (isTTY) stdin.setRawMode(false);
          stdin.pause();
          stdin.off('data', onData);
          process.stdout.write('\n');
          resolve(value);
          return;
        }
        if (char === '\u0003') process.exit(130); // Ctrl+C
        if (char === '\u007f' || char === '\b') value = value.slice(0, -1);
        else value += char;
      }
    };
    stdin.on('data', onData);
  });
}

const password = await askHidden('Neues Dev-Passwort: ');
if (password.length < 6) {
  console.error('Das Passwort muss mindestens 6 Zeichen lang sein.');
  process.exit(1);
}
const repeat = await askHidden('Passwort wiederholen: ');
if (repeat !== password) {
  console.error('Die Passwörter stimmen nicht überein.');
  process.exit(1);
}

const salt = randomBytes(16).toString('hex');
const hash = passwordHash(salt, password);
writeFileSync(
  target,
  `/**
 * Dev-mode password. Generated by \`npm run dev:password\` — do not edit by hand.
 * Only a salted SHA-256 hash is stored, never the password itself.
 * Empty hash = no password set yet (dev mode cannot be unlocked).
 */
export const DEV_PASSWORD = { salt: '${salt}', hash: '${hash}' };
`,
);
console.log('Gespeichert in src/dev/devPassword.ts. Committen und deployen, damit es online gilt.');
